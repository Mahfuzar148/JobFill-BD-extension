// Lookup indexes for accelerated execution
const CANONICAL_BY_ID = new Map<string, UniversalCanonicalField>();
const CANONICAL_BY_LEGACY = new Map<string, UniversalCanonicalField>();

for (const field of UNIVERSAL_FIELD_REGISTRY) {
  CANONICAL_BY_ID.set(field.canonicalId, field);
  for (const legacy of field.legacyCanonicalIds) {
    CANONICAL_BY_LEGACY.set(legacy, field);
  }
}

export class UniversalFieldRegistry {
  public static getField(canonicalId: string): UniversalCanonicalField | undefined {
    return CANONICAL_BY_ID.get(canonicalId) || CANONICAL_BY_LEGACY.get(canonicalId);
  }

  public static getAllFields(): UniversalCanonicalField[] {
    return UNIVERSAL_FIELD_REGISTRY;
  }

  public static getFieldsByCategory(category: UniversalCanonicalField['category']): UniversalCanonicalField[] {
    return UNIVERSAL_FIELD_REGISTRY.filter((f) => f.category === category);
  }

  public static getCanonicalIdForLegacy(legacyId: string): string {
    const field = CANONICAL_BY_LEGACY.get(legacyId);
    return field ? field.canonicalId : legacyId;
  }
}
