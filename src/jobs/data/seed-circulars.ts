/**
 * Idempotently seeds all default lifecycle stores (Exam Schedules, Admit Cards, Seat Plans, Job Results)
 * if they are currently unpopulated in storage.
 */
export async function seedDefaultLifecycleStores(): Promise<void> {
  try {
    const {
      ExamScheduleRepository,
      AdmitCardNoticeRepository,
      SeatPlanNoticeRepository,
      JobResultRepository,
      examScheduleRepository,
      admitCardNoticeRepository,
      seatPlanNoticeRepository,
      jobResultRepository,
    } = await import('../database/job-lifecycle-repository');

    const [existingExams, existingAdmits, existingSeats, existingResults] = await Promise.all([
      examScheduleRepository.getAll(),
      admitCardNoticeRepository.getAll(),
      seatPlanNoticeRepository.getAll(),
      jobResultRepository.getAll(),
    ]);

    const tasks: Promise<any>[] = [];
    if (existingExams.length === 0) {
      tasks.push(ExamScheduleRepository.saveMany(ALL_SEED_EXAM_SCHEDULES));
    }
    if (existingAdmits.length === 0) {
      tasks.push(AdmitCardNoticeRepository.saveMany(ALL_SEED_ADMIT_CARDS));
    }
    if (existingSeats.length === 0) {
      tasks.push(SeatPlanNoticeRepository.saveMany(ALL_SEED_SEAT_PLANS));
    }
    if (existingResults.length === 0) {
      tasks.push(JobResultRepository.saveMany(ALL_SEED_JOB_RESULTS));
    }

    if (tasks.length > 0) {
      await Promise.all(tasks);
    }
  } catch (err) {
    console.warn('JobFill BD [seedDefaultLifecycleStores]: lifecycle store initialization error:', err);
  }
}
